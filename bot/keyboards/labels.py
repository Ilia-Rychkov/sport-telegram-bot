def make_button(label: str) -> KeyboardButton:
    return KeyboardButton(text=DISPLAY_LABELS.get(label, label))


async def normalize_button_input(handler, message: Message, data):
    label = LABELS_BY_DISPLAY.get(message.text)
    if label is not None:
        message = message.model_copy(update={"text": label})
    return await handler(message, data)
